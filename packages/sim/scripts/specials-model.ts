// Fits the specials inference model: how often a player who could play the Tiger, Bull or
// Bear does so, by situation, from self-play. Writes packages/bots/src/inference/generated/.
// Usage: tsx scripts/specials-model.ts [spec=hard] [hands=1500]  (env WORKERS, SEED, OUT)
import { writeFileSync } from 'node:fs';
import { COARSE_CELLS, FINE_CELLS, SPECIALS } from '@mam/bots';
import { handStarts, makeBoards } from '../src/duplicate';
import { defaultWorkers, runParallel } from '../src/parallel';
import type { SpecialsRow } from '../src/tasks';
import '../src/registry';

const [spec = 'hard', handsArg = '1500'] = process.argv.slice(2);
const count = Number(handsArg);
const seed = process.env.SEED ?? 'specials';
const workers = Number(process.env.WORKERS ?? defaultWorkers());
const out =
  process.env.OUT ??
  new URL('../../bots/src/inference/generated/specialsModel.ts', import.meta.url).pathname;
/** Pseudo-counts pulling a sparse cell toward its coarser parent. */
const K = 8;

const pool = await runParallel(
  'play',
  Array.from({ length: 200 }, (_, i) => ({
    seed: `${seed}:pool:${i}`,
    dealer: (i % 4) as 0 | 1 | 2 | 3,
    specs: ['normal', 'normal', 'normal', 'normal'] as const,
  })),
  { workers },
);
const boards = makeBoards(count, seed, handStarts(pool));
const t0 = performance.now();
const results = await runParallel(
  'specials',
  boards.map((b) => ({
    seed: b.seed,
    dealer: b.dealer,
    scores: b.scores,
    hands: 1,
    specs: [spec, spec, spec, spec] as const,
  })),
  { workers },
);
const rows: SpecialsRow[] = results.flat();

const perSpecial = COARSE_CELLS / SPECIALS.length;
const fineN = new Array(FINE_CELLS).fill(0);
const fineK = new Array(FINE_CELLS).fill(0);
const coarseN = new Array(COARSE_CELLS).fill(0);
const coarseK = new Array(COARSE_CELLS).fill(0);
const baseN = SPECIALS.map(() => 0);
const baseK = SPECIALS.map(() => 0);
// Each fine cell's coarse parent, read off the rows (both are computed by `opportunity`).
const parent = new Array(FINE_CELLS).fill(-1);
for (const [fine, coarse, played] of rows) {
  fineN[fine] += 1;
  fineK[fine] += played;
  coarseN[coarse] += 1;
  coarseK[coarse] += played;
  parent[fine] = coarse;
  const s = Math.floor(coarse / perSpecial);
  baseN[s] = (baseN[s] as number) + 1;
  baseK[s] = (baseK[s] as number) + played;
}
const base = SPECIALS.map((_, s) => ((baseK[s] as number) + 0.5) / ((baseN[s] as number) + 1));
const pCoarse = coarseN.map((n, c) => {
  const b = base[Math.floor(c / perSpecial)] as number;
  return (coarseK[c] + K * b) / (n + K);
});
const finePerSpecial = FINE_CELLS / SPECIALS.length;
const pPlay = fineN.map((n, f) => {
  // A cell never seen falls back to its special's base rate.
  const prior =
    parent[f] >= 0
      ? (pCoarse[parent[f]] as number)
      : (base[Math.floor(f / finePerSpecial)] as number);
  return Math.round(((fineK[f] + K * prior) / (n + K)) * 1e4) / 1e4;
});

const source = `${spec} self-play, ${count} hands, ${rows.length} opportunities`;
writeFileSync(
  out,
  `// Generated by \`packages/sim/scripts/specials-model.ts\`. Do not edit by hand.\nimport type { SpecialsModel } from '../specials';\n\nexport const SPECIALS_MODEL: SpecialsModel = {\n  source: ${JSON.stringify(source)},\n  pPlay: ${JSON.stringify(pPlay)},\n};\n`,
);
console.log(`${source} in ${((performance.now() - t0) / 1000).toFixed(0)}s → ${out}`);
const names = ['tiger', 'bull', 'bear'];
const rel = ['nobody winning', 'partner winning', 'opponent winning'];
const money = ['$0', '≤$20k', '≤$40k', '≤$70k', '>$70k'];
SPECIALS.forEach((_, s) => {
  console.log(
    `  ${names[s]}: ${baseN[s]} opportunities, played ${(100 * (base[s] as number)).toFixed(1)}%`,
  );
  for (let c = s * perSpecial; c < (s + 1) * perSpecial; c++) {
    if (coarseN[c] < 20) continue;
    const r = Math.floor((c % perSpecial) / (2 * 5));
    const last = Math.floor((c % 10) / 5) === 1;
    const m = c % 5;
    console.log(
      `    ${rel[r]?.padEnd(17)} ${last ? 'last ' : 'early'} ${money[m]?.padEnd(6)} n=${String(coarseN[c]).padStart(5)} played ${(100 * (pCoarse[c] as number)).toFixed(1)}%`,
    );
  }
});
